os.makedirs(DOWNLOAD_FOLDER, exist_ok=True)


async def download_file(session, url):
    filename = os.path.join(DOWNLOAD_FOLDER, url.split("/")[-1])

    if os.path.exists(filename):
        print(f"Already exists: {filename}")
        return
    try:
        async with session.get(url, timeout=aiohttp.ClientTimeout(total=DOWNLOAD_TIMEOUT_S)) as response:
            response.raise_for_status()
            with open(filename, "wb") as f:
                while True:
                    chunk = await response.content.read(READ_CHUNK_BYTES)
                    if not chunk:
                        break
                    f.write(chunk)
        print(f"Downloaded: {filename}")
    except Exception as e:
        print(f"Failed to download {filename}: {e}")


async def bound_download(sem, session, url):
    async with sem:
        await download_file(session, url)


async def main():
    sem = asyncio.Semaphore(MAX_CONCURRENT_DOWNLOADS)
    async with aiohttp.ClientSession() as session:
        tasks = [bound_download(sem, session, url) for url in URLS]
        await asyncio.gather(*tasks)


if __name__ == "__main__":
    asyncio.run(main())
